COPYRIGHT_LINE = re.compile(
    r"(?i)^\s*(/\*|//|\*)\s*.*(copyright|licensed under|apache license|mit license|"
    r"all rights reserved|created by|generated by|@author\b).*$"
)
BLOCK_COMMENT_START = re.compile(r"^\s*/\*+")
BLOCK_COMMENT_END = re.compile(r"\*/\s*$")


def clean_source(text: str) -> list[str]:
    lines = text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    out: list[str] = []
    in_block = False
    block_buf: list[str] = []
    for raw in lines:
        line = raw.rstrip()
        if in_block:
            block_buf.append(line)
            if BLOCK_COMMENT_END.search(line):
                in_block = False
                block_text = "\n".join(block_buf)
                # drop license/copyright blocks; keep short javadoc if not copyright-ish
                joined = " ".join(block_buf).lower()
                if any(
                    k in joined
                    for k in (
                        "copyright",
                        "licensed under",
                        "apache license",
                        "mit license",
                        "all rights reserved",
                    )
                ):
                    block_buf = []
                    continue
                # keep compact class-level doc if short
                if len(block_buf) <= 8:
                    for b in block_buf:
                        if b.strip():
                            out.append(b)
                block_buf = []
            continue
        if BLOCK_COMMENT_START.match(line) and "/*" in line and "*/" not in line:
            in_block = True
            block_buf = [line]
            continue
        if "/*" in line and "*/" in line:
            joined = line.lower()
            if any(k in joined for k in ("copyright", "licensed under", "apache")):
                continue
        if COPYRIGHT_LINE.match(line):
            continue
        # strip pure decorative blank spam later
        out.append(line)

    # collapse multiple blank lines to at most one; then remove leading/trailing blanks of file
    compact: list[str] = []
    prev_blank = False
    for line in out:
        blank = not line.strip()
        if blank and prev_blank:
            continue
        compact.append(line)
        prev_blank = blank
    while compact and not compact[0].strip():
        compact.pop(0)
    while compact and not compact[-1].strip():
        compact.pop()
    return compact


def collect_lines() -> list[str]:
    all_lines: list[str] = []
    missing = []
    for rel in FILE_GLOBS:
        path = ROOT / rel
        if not path.exists():
            missing.append(rel)
            continue
        body = path.read_text(encoding="utf-8", errors="ignore")
        cleaned = clean_source(body)
        if not cleaned:
            continue
        all_lines.append(f"// ===== {rel.replace(chr(92), '/')} =====")
        all_lines.extend(cleaned)
        all_lines.append("")  # single separator blank
    if missing:
        print("MISSING:", *missing, sep="\n  ")
    # final collapse
    compact: list[str] = []
    prev_blank = False
    for line in all_lines:
        blank = not line.strip()
        if blank and prev_blank:
            continue
        compact.append(line.rstrip("\n"))
        prev_blank = blank
    return compact


def paginate(lines: list[str]) -> list[list[str]]:
    pages: list[list[str]] = []
    for i in range(0, len(lines), LINES_PER_PAGE):
        pages.append(lines[i : i + LINES_PER_PAGE])
    return pages


def select_pages(pages: list[list[str]]) -> list[list[str]]:
    if len(pages) <= FRONT_PAGES + BACK_PAGES:
        return pages
    return pages[:FRONT_PAGES] + pages[-BACK_PAGES:]


def set_run_font(run, name_cn="宋体", name_ascii="Courier New", size=10.5):
    run.font.size = Pt(size)
    run.font.name = name_ascii
    r = run._element
    rPr = r.get_or_add_rPr()
    rFonts = rPr.get_or_add_rFonts()
    rFonts.set(qn("w:ascii"), name_ascii)
    rFonts.set(qn("w:hAnsi"), name_ascii)
    rFonts.set(qn("w:eastAsia"), name_cn)


def add_page_number(paragraph):
    """Insert PAGE field at end of paragraph."""
    run = paragraph.add_run()
    fld_char_begin = OxmlElement("w:fldChar")
    fld_char_begin.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = " PAGE "
    fld_char_end = OxmlElement("w:fldChar")
    fld_char_end.set(qn("w:fldCharType"), "end")
    run._r.append(fld_char_begin)
    run._r.append(instr)
    run._r.append(fld_char_end)
    set_run_font(run)


def setup_header(section):
    header = section.header
    header.is_linked_to_previous = False
    p = header.paragraphs[0] if header.paragraphs else header.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    # clear
    p.clear()
    left = p.add_run("【软件全称】  【版本号】")
    set_run_font(left, size=9)
    # tab to right for page num — use right-aligned second paragraph simpler
    p2 = header.add_paragraph()
    p2.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    label = p2.add_run("第 ")
    set_run_font(label, size=9)
    add_page_number(p2)
    label2 = p2.add_run(" 页")
    set_run_font(label2, size=9)


def build_doc(pages: list[list[str]]):
    doc = Document()
    section = doc.sections[0]
    section.top_margin = Cm(1.5)
    section.bottom_margin = Cm(1.5)
    section.left_margin = Cm(1.8)
    section.right_margin = Cm(1.8)
    setup_header(section)

    # cover note (not counted as code pages — user template style)
    note = doc.add_paragraph()
    nr = note.add_run(
        "（材料说明：若全部代码未超过约 3000 行则提交全部；超过则提交连续源码流的前 30 页与后 30 页。"
        "每页不少于 50 行（结束页除外）。页眉左侧为软件全称与版本号，右上为页码。"
        "软件全称/版本号/开发完成日期/著作权人待申请表定稿后回填页眉。）"
    )
    set_run_font(nr, name_ascii="宋体", size=10.5)
    doc.add_paragraph()

    for pi, page_lines in enumerate(pages):
        if pi > 0:
            doc.add_page_break()
        for line in page_lines:
            para = doc.add_paragraph()
            pf = para.paragraph_format
            pf.space_before = Pt(0)
            pf.space_after = Pt(0)
            pf.line_spacing_rule = WD_LINE_SPACING.EXACTLY
            pf.line_spacing = Pt(12)
            # keep empty lines as blank paragraph for row count
            run = para.add_run(line if line.strip() else " ")
            set_run_font(run, size=9)
    doc.save(OUT)
    return OUT


def main():
    lines = collect_lines()
    pages_all = paginate(lines)
    pages = select_pages(pages_all)
    # ensure last page ends with content (module end ideally)
    path = build_doc(pages)
    print(f"files_ok lines={len(lines)} pages_all={len(pages_all)} pages_out={len(pages)}")
    print(f"wrote {path}")
    # stats last page lines
    print(f"last_page_lines={len(pages[-1])} first_page_lines={len(pages[0])}")


if __name__ == "__main__":
    main()
